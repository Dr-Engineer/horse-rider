WIDTH, HEIGHT = 7, 9
ADVANCE = 8
NARROW = {".": (2, 4), ",": (1, 4), "!": (2, 5), ":": (2, 4), "'": (1, 4), "(": (1, 6), ")": (1, 6), " ": (0, 5)}
COLS = 16
REVISION = 3   # bump when glyph art changes: Godot re-imports a BMFont only when the .fnt text changes


def save_png_rgba(path, width, height, pixels):
    raw = bytearray()
    for y in range(height):
        raw.append(0)
        raw.extend(pixels[y * width * 4:(y + 1) * width * 4])

    def chunk(tag, data):
        body = tag + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)

    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)))
        f.write(chunk(b"IDAT", zlib.compress(bytes(raw), 9)))
        f.write(chunk(b"IEND", b""))


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    chars = sorted(GLYPHS.keys(), key=ord)
    # Lower case maps onto the same glyphs, all in-game lettering is capitals.
    rows = (len(chars) // COLS) + 1
    cell_w, cell_h = WIDTH + 2, HEIGHT + 2
    tex_w, tex_h = 256, 128
    assert COLS * cell_w <= tex_w and rows * cell_h <= tex_h
    pixels = bytearray(tex_w * tex_h * 4)
    lines = [
        'info face="Headline" size=%d bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=0 padding=0,0,0,0 spacing=1,1 outline=0 rev=%d' % (HEIGHT + 2, REVISION),
        "common lineHeight=%d base=%d scaleW=%d scaleH=%d pages=1 packed=0" % (HEIGHT + 3, HEIGHT, tex_w, tex_h),
        'page id=0 file="headline.png"',
    ]
    entries = []
    for i, ch in enumerate(chars):
        cx, cy = (i % COLS) * cell_w + 1, (i // COLS) * cell_h + 1
        rows_data = GLYPHS[ch]
        assert len(rows_data) == HEIGHT and all(len(r) == WIDTH for r in rows_data), ch
        offset, adv = NARROW.get(ch, (0, ADVANCE))
        for y, row in enumerate(rows_data):
            for x, c in enumerate(row):
                if c == "#":
                    p = ((cy + y) * tex_w + cx + x) * 4
                    pixels[p:p + 4] = bytes((255, 255, 255, 255))
        codes = [ord(ch)]
        if ch.isalpha():
            codes.append(ord(ch.lower()))
        for code in codes:
            entries.append(
                "char id=%d x=%d y=%d width=%d height=%d xoffset=%d yoffset=0 xadvance=%d page=0 chnl=15"
                % (code, cx, cy, WIDTH, HEIGHT, -offset if offset else 0, adv)
            )
    lines.append("chars count=%d" % len(entries))
    lines.extend(entries)
    save_png_rgba(os.path.join(OUT_DIR, "headline.png"), tex_w, tex_h, pixels)
    with open(os.path.join(OUT_DIR, "headline.fnt"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("font: %d glyph entries" % len(entries))


if __name__ == "__main__":
    main()
